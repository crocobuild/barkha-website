/**
 * Asset pipeline.
 *  - Photos  → public/img/<name>-<w>.{avif,webp} + a tiny blur placeholder
 *  - Medallions (cream line-art on taupe) → traced SVG path data so the
 *    lines can draw themselves on screen.
 * Writes src/content/assets.gen.ts (typed manifest). Run: npm run assets
 */
import { mkdir, readdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import sharp from 'sharp'
import potrace from 'potrace'

const ROOT = path.resolve(import.meta.dirname, '..')
const SRC = path.join(ROOT, 'assets-src')
const OUT = path.join(ROOT, 'public/img')
const WIDTHS = [480, 960, 1440, 2200]

type Photo = { w: number; h: number; widths: number[]; blur: string }

const trace = (buf: Buffer) =>
  new Promise<string>((resolve, reject) =>
    potrace.trace(buf, { threshold: 150, turdSize: 6, optTolerance: 0.35, color: 'currentColor' }, (err: Error | null, svg: string) =>
      err ? reject(err) : resolve(svg),
    ),
  )

async function photo(file: string, name: string): Promise<Photo> {
  let img = sharp(path.join(SRC, file)).rotate()
  // The portrait sits inside a white paper frame; trim it away.
  if (name === 'barkha-portrait') img = sharp(await img.trim({ threshold: 30 }).toBuffer())
  const { width = 0, height = 0 } = await img.metadata()
  const widths = WIDTHS.filter((w) => w < width)
    .concat(width)
    .filter((w, i, a) => a.indexOf(w) === i)
  for (const w of widths) {
    const r = img.clone().resize({ width: w })
    await r
      .clone()
      .avif({ quality: 52, effort: 6 })
      .toFile(path.join(OUT, `${name}-${w}.avif`))
    await r
      .clone()
      .webp({ quality: 74 })
      .toFile(path.join(OUT, `${name}-${w}.webp`))
  }
  const tiny = await img.clone().resize({ width: 24 }).blur(1.2).webp({ quality: 40 }).toBuffer()
  return { w: width, h: height, widths, blur: `data:image/webp;base64,${tiny.toString('base64')}` }
}

async function medallion(file: string): Promise<string[]> {
  // Lines are light on dark: negate so potrace traces the lines themselves.
  const buf = await sharp(path.join(SRC, file)).resize(1440).greyscale().negate().normalise().png().toBuffer()
  const svg = await trace(buf)
  const d = [...svg.matchAll(/ d="([^"]+)"/g)].map((m) => m[1])
  // Split the compound path into sub-paths so each stroke can be staggered.
  return d
    .flatMap((p) =>
      p
        .split(/(?=M)/)
        .map((s) => s.trim())
        .filter((s) => s.length > 40),
    )
    .map((p) => p.replace(/-?\d+\.\d+/g, (n) => String(Math.round(+n * 10) / 10)))
}

async function main() {
  await mkdir(OUT, { recursive: true })
  const files = (await readdir(SRC)).filter((f) => /\.(jpe?g|png)$/i.test(f)).sort()
  const photos: Record<string, Photo> = {}
  const medallions: Record<string, string[]> = {}
  for (const f of files) {
    const name = f.replace(/\.\w+$/, '')
    if (name.startsWith('med-')) {
      medallions[name.slice(4)] = await medallion(f)
      console.log('traced', name, medallions[name.slice(4)].length, 'paths')
    } else {
      photos[name] = await photo(f, name)
      console.log('photo ', name, photos[name].widths.join(','))
    }
  }
  const MED = path.join(ROOT, 'src/content/medallions')
  await mkdir(MED, { recursive: true })
  for (const [name, paths] of Object.entries(medallions)) {
    // One lazily-imported module per medallion keeps the main bundle light.
    await writeFile(path.join(MED, `${name}.ts`), `// Generated. viewBox 0 0 1440 1440\nexport default ${JSON.stringify(paths)}\n`)
    const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1440 1440" width="720" height="720"><rect width="1440" height="1440" fill="#F2ECE2"/><path d="${paths.join(' ')}" fill="none" stroke="#3B2F25" stroke-width="2"/></svg>`
    if (process.env.PREVIEW)
      await sharp(Buffer.from(svg))
        .png()
        .toFile(path.join(process.env.PREVIEW, `${name}.png`))
  }
  const ts = `// Generated by scripts/build-assets.ts — do not edit by hand.
export const photos = ${JSON.stringify(photos, null, 1)} as const

export type PhotoName = keyof typeof photos

export const medallionNames = ${JSON.stringify(Object.keys(medallions))} as const

export type MedallionName = (typeof medallionNames)[number]
`
  await writeFile(path.join(ROOT, 'src/content/assets.gen.ts'), ts)
}

main().catch((e) => {
  console.error(e)
  process.exit(1)
})
